"""Extract literal layout observations; never calculate expected geometry."""
import argparse,base64,gzip,hashlib,json
from pathlib import Path

root=Path(__file__).resolve().parents[1]
source=root/'research/kitty-reference-evidence/d638691-observations.json.gz'
digest='b00df940a8d246bfdc958ea46d67d8321d031d129b02db28cc2fe3b298a176a0'
raw=gzip.decompress(source.read_bytes());assert hashlib.sha256(raw).hexdigest()==digest
data=json.loads(raw)
assert data['status']=='complete' and data['upstream_commit']=='8e5487e9d4a1dd79c3a769e0ba82326b8ad7c37f'
assert data['upstream_tests']['successful'] and not data['upstream_tests']['skipped']
names=('natural-one-cell','natural-two-by-three','both-axes-different-aspect',
       'columns-only','rows-only','native-pixel-offset','both-axes-pixel-offset',
       'columns-pixel-offset','rows-pixel-offset','clamped-pixel-offset',
       'crop-and-resize','no-cursor-movement','right-edge-wrap')
lines=['/* Generated by scripts/generate-kitty-layout-reference.py.',
       ' * Literal compiled-kitty observations, SHA-256 '+digest+'.',
       ' * No OS window/GPU pixels; bottom-scroll belongs to the future owner. */',
       'static const Reference references[] = {']
for name in names:
    case=next(c for c in data['cases'] if c['name']==name);assert len(case['steps'])==1
    state=case['steps'][0];assert len(state['layers'])==1
    encoded=base64.b64decode(state['input_base64']);assert encoded.startswith(b'\x1b_G')
    header=encoded[3:].split(b';',1)[0].decode('ascii')
    values=dict(part.split('=') for part in header.split(','))
    rect=state['pixel_boxes'][0];src=state['layers'][0]['src_rect']
    scalar=[values['s'],values['v'],*map(str,case['start']),*map(str,state['cursor'])]
    rectangles=['{'+','.join(repr(r[k]) for k in ('left','top','right','bottom'))+'}' for r in (rect,src)]
    lines.append('    {'+','.join([json.dumps(name),json.dumps(header),*scalar,*rectangles])+'},')
lines.append('};\n');expected='\n'.join(lines)
target=root/'tests/kitty_layout_reference.h'
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
if args.check:
    assert target.read_text(encoding='utf-8')==expected,'Regenerate kitty layout observations'
    print('Pinned kitty layout reference: 13 literal observations verified')
else:target.write_bytes(expected.encode('utf-8'))
