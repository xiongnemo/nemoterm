"""Generate compact UAX #29 properties from pinned, local Unicode data.

No network access. Check every input against the committed download manifest.
The terminal's older wcwidth tables are independent and are not changed here.
"""
import argparse
from array import array
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'tools/unicode/18.0.0'
OUTPUT = ROOT / 'vendor/putty-0.85/terminal/nemo_grapheme_data.h'
GCB = ('Other', 'CR', 'LF', 'Control', 'Extend', 'ZWJ',
       'Regional_Indicator', 'Prepend', 'SpacingMark', 'L', 'V', 'T', 'LV', 'LVT')
INCB = ('None', 'Consonant', 'Extend', 'Linker')


def records(name):
    for line in (DATA / name).read_text(encoding='utf-8').splitlines():
        fields = [s.strip() for s in line.partition('#')[0].split(';')]
        if not fields[0]:
            continue
        bounds = fields[0].split('..')
        yield int(bounds[0], 16), int(bounds[-1], 16), fields[1:]


def generate():
    for item in json.loads((DATA / 'manifest.json').read_text()):
        data = (DATA / item['file']).read_bytes()
        if len(data) != item['bytes'] or hashlib.sha256(data).hexdigest() != item['sha256']:
            raise ValueError(f"Unicode input changed: {item['file']}")
    properties = array('H', [0]) * 0x110000
    for lo, hi, fields in records('GraphemeBreakProperty.txt'):
        value = GCB.index(fields[0])
        # Hangul syllables alternate every 28 code points. Compute their GCB
        # rather than storing almost 800 tiny ranges.
        if fields[0] in ('LV', 'LVT'):
            assert 0xac00 <= lo <= hi <= 0xd7a3
            continue
        for cp in range(lo, hi+1):
            assert not properties[cp]
            properties[cp] = value
    for lo, hi, fields in records('DerivedCoreProperties.txt'):
        if fields[0] == 'InCB':
            for cp in range(lo, hi+1):
                assert not properties[cp] & 0x30
                properties[cp] |= INCB.index(fields[1]) << 4
    for lo, hi, fields in records('emoji-data.txt'):
        bit = {'Extended_Pictographic': 0x40, 'Emoji_Presentation': 0x80,
               'Emoji': 0x100}.get(fields[0], 0)
        if bit:
            for cp in range(lo, hi+1):
                properties[cp] |= bit
    for lo, hi, fields in records('EastAsianWidth.txt'):
        if fields[0] in ('W', 'F'):
            for cp in range(lo, hi+1):
                properties[cp] |= 0x200
    rows = []
    lo = 0
    while lo < len(properties):
        hi = lo+1
        while hi < len(properties) and properties[hi] == properties[lo]:
            hi += 1
        if properties[lo]:
            rows.append(f'    {{0x{lo:06x}, 0x{hi-1:06x}, 0x{properties[lo]:02x}}},')
        lo = hi
    return '\n'.join([
        '/* Generated by scripts/generate-grapheme-tables.py; do not edit.',
        ' * Unicode 18.0.0. Copyright 1991-2026 Unicode, Inc.',
        ' * SPDX-License-Identifier: Unicode-3.0',
        ' * See tools/unicode/18.0.0/LICENSE.txt and manifest.json. */',
        'static const struct { uint32_t first, last; uint16_t value; }',
        'nemo_grapheme_ranges[] = {', *rows, '};', ''])


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    generated = generate()
    if args.check:
        if OUTPUT.read_text(encoding='utf-8') != generated:
            raise SystemExit('Grapheme tables are stale; regenerate them')
    else:
        OUTPUT.write_text(generated, encoding='utf-8', newline='\n')
    print(f'Unicode 18.0.0 grapheme tables: {len(generated.splitlines())-7} ranges')
