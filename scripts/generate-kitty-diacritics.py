"""Generate the small protocol numeric alphabet from the pinned capture."""
import argparse
import hashlib
import json
from pathlib import Path
import tarfile

root = Path(__file__).resolve().parents[1]
digest = 'feda36b2971fbc29059b4c80ddf989c228e8c4b5c18ffe07fb064b05bbd78a44'
with tarfile.open(root / 'research/kitty-unicode-evidence/upstream-reference.tar.gz') as tar:
    raw = tar.extractfile('reference/observations.json').read()
assert hashlib.sha256(raw).hexdigest() == digest
points = json.loads(raw)['diacritic_codepoints']
assert len(points) == 297 and points == sorted(set(points))
lines = ['/* Generated by scripts/generate-kitty-diacritics.py.',
         ' * Protocol alphabet derived from Unicode 6.0.0; pinned capture SHA256',
         ' * ' + digest + '. */',
         'static const uint32_t nemo_kitty_diacritics[] = {']
lines += ['    ' + ','.join('0x%x' % p for p in points[i:i+8]) + ','
          for i in range(0, len(points), 8)]
text = '\n'.join(lines + ['};', ''])
path = root / 'vendor/putty-0.85/terminal/nemo_kitty_diacritics.h'
parser = argparse.ArgumentParser()
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
if args.check:
    assert path.read_text() == text
else:
    path.write_text(text)
print('Verified all 297 protocol diacritics against the pinned capture')
