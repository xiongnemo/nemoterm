"""Validate UI translations and emit a deterministic, code-page independent C table."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUTPUT = ROOT / "vendor/putty-0.85/utils/nemo_ui_catalog.h"


def unique(pairs):
    result = {}
    for key, value in pairs:
        if key in result:
            raise ValueError(f"Duplicate JSON key: {key}")
        result[key] = value
    return result


def parameters(text):
    keys = set(re.findall(r"\{([a-z][a-z0-9_]*)\}", text))
    if re.search(r"[{}]", re.sub(r"\{[a-z][a-z0-9_]*\}", "", text)):
        raise ValueError(f"Invalid named template: {text}")
    return keys


def literal(text):
    return '"' + ''.join(chr(b) if 32 <= b < 127 and b not in (34, 92)
                         else f"\\{b:03o}" for b in text.encode("utf-8")) + '"'


def generate(directory=ROOT / "locales"):
    catalogs = [json.loads((directory / f"{lang}.json").read_text(encoding="utf-8"),
                           object_pairs_hook=unique) for lang in ("en", "zh-CN")]
    for lang, catalog in zip(("en", "zh-CN"), catalogs):
        if catalog["schema"] != 1 or catalog["locale"] != lang:
            raise ValueError(f"Invalid catalog header: {lang}")
    en, zh = (c["messages"] for c in catalogs)
    if en.keys() != zh.keys():
        raise ValueError(f"Catalog keys differ: {en.keys() ^ zh.keys()}")
    rows = []
    for key in sorted(en):
        if not re.fullmatch(r"[a-z][a-z0-9_.]*", key):
            raise ValueError(f"Invalid message ID: {key}")
        if not isinstance(en[key], str) or not en[key] or not isinstance(zh[key], str):
            raise ValueError(f"Invalid message: {key}")
        if parameters(en[key]) != parameters(zh[key] or en[key]):
            raise ValueError(f"Template parameters differ: {key}")
        rows.append("    {" + ", ".join(literal(v) for v in (key, en[key], zh[key])) + "},")
    return ("/* Generated by scripts/generate-ui-catalog.py; do not edit. */\n"
            "static const struct NemoUIEntry { const char *id, *en, *zh; } nemo_ui_catalog[] = {\n"
            + "\n".join(rows) + "\n};\n")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    content = generate()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="ascii") != content:
            raise SystemExit("UI catalog is stale; run scripts/generate-ui-catalog.py")
    else:
        OUTPUT.write_text(content, encoding="ascii", newline="\n")
    print("UI catalogs validated")
