"""Generate bounded, read-only X11 colour data from pinned Xorg source.

No network access or terminal execution. The C test vectors are source-derived
expectations, not an independently captured XTerm oracle.
"""
import argparse
import hashlib
import json
from pathlib import Path
import re

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'tools/x11/xorg-server-21.1.16'


def records():
    manifest = json.loads((DATA / 'manifest.json').read_text(encoding='utf-8'))
    for item in manifest['files']:
        data = (DATA / item['file']).read_bytes()
        if len(data) != item['bytes'] or hashlib.sha256(data).hexdigest() != item['sha256']:
            raise ValueError('Pinned Xorg input changed: ' + item['file'])
    source = (DATA / 'oscolor.c').read_text(encoding='utf-8')
    names_body = source.split('static const char BuiltinColorNames[] = {', 1)[1].split('};', 1)[0]
    literals = re.findall(r'"([A-Za-z0-9 ]+)\\0"', names_body)
    if re.sub(r'"[A-Za-z0-9 ]+\\0"|\s', '', names_body):
        raise ValueError('Unexpected colour string syntax')
    names, offset = {}, 0
    for name in literals:
        names[offset] = name
        offset += len(name) + 1
    body = source.split('static const BuiltinColor BuiltinColors[] = {', 1)[1].split('};', 1)[0]
    pattern = r'\{(\d+),\s*(\d+),\s*(\d+),\s*(\d+)\},\s*/\* ([A-Za-z0-9 ]+) \*/'
    if re.sub(pattern + r'|\s', '', body):
        raise ValueError('Unexpected colour table syntax')
    result = []
    for red, green, blue, pos, comment in re.findall(pattern, body):
        name = names.pop(int(pos))
        if name != comment:
            raise ValueError('Offset/name mismatch')
        rgb = tuple(map(int, (red, green, blue)))
        if any(c > 255 for c in rgb):
            raise ValueError('Invalid RGB channel')
        result.append((name, rgb))
    keys = [name.lower() for name, _ in result]
    if names or not result or keys != sorted(set(keys)) or offset > 65535:
        raise ValueError('Incomplete, unsorted or oversized table')
    return result


def generate(rows):
    notice = [
        '/* Generated by scripts/generate-x11-colours.py; do not edit.',
        ' * Xorg server 21.1.16 os/oscolor.c colour data.',
        ' * Copyright 1987, 1998 The Open Group.',
        ' * Copyright 1987 Digital Equipment Corporation.',
        ' * See tools/x11/xorg-server-21.1.16/LICENSE.txt and manifest.json. */',
    ]
    maximum = max(len(name) for name, _ in rows)
    data = notice + [f'#define NEMO_X11_COLOUR_MAX_NAME {maximum}',
                     'static const char nemo_x11_colour_names[] = {']
    # Adjacent string literals become one literal; 7614 bytes exceeds the
    # ISO C99 minimum supported length (4095). Keep identical packed bytes
    # using individual character initializers, including the final sentinel.
    data += ['    ' + ', '.join(repr(c) for c in name.lower()) + ', 0,'
             for name, _ in rows]
    data += ['    0', '};', 'static const struct { uint16_t offset; uint8_t r, g, b; }',
             'nemo_x11_colours[] = {']
    offset = 0
    for name, (r, g, b) in rows:
        data.append(f'    {{{offset}, {r}, {g}, {b}}},')
        offset += len(name) + 1
    data += ['};', '']
    tests = notice + ['/* Source-derived vectors; runtime verification is separate. */',
                      'static const struct { const char *name; unsigned r, g, b; }',
                      'x11_colour_cases[] = {']
    tests += [f'    {{"{name}", {r}, {g}, {b}}},' for name, (r, g, b) in rows]
    tests += ['};', '']
    return {
        ROOT / 'vendor/putty-0.85/terminal/nemo_x11_colour_data.h': '\n'.join(data),
        ROOT / 'tests/x11_colour_cases.h': '\n'.join(tests),
    }


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    rows = records()
    for path, text in generate(rows).items():
        if args.check:
            if path.read_text(encoding='utf-8') != text:
                raise SystemExit('Stale generated file: ' + str(path))
        else:
            path.write_text(text, encoding='utf-8', newline='\n')
    print(f'{len(rows)} X11 names; maximum {max(len(n) for n, _ in rows)} bytes; '
          f'{sum(len(n)+1 for n, _ in rows)+1} string bytes')
