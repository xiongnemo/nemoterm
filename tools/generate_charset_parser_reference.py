"""Derive parser framing from the same pinned XTerm captures as the cell table."""
import argparse
import hashlib
import json
import re
from pathlib import Path

root = Path(__file__).resolve().parents[1]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('captures', type=Path)
args = parser.parse_args()
source = (root/'tests/charset_reference.h').read_text()
cases = {}
for name, digest in re.findall(r'\* (charsets-canonical-\d.json): ([0-9a-f]{64})', source):
    path = args.captures/name
    assert hashlib.sha256(path.read_bytes()).hexdigest() == digest, name
    cases.update(json.loads(path.read_text())['cases'])

def literal(data):
    return '"'+''.join(chr(c) if 32 <= c < 127 and c not in (34,92)
                       else '\\%03o' % c for c in data)+'"'

out = ('/* Generated by tools/generate_charset_parser_reference.py from the pinned\n'
       ' * captures named in charset_reference.h. Same case order and selection. */\n'
       'static const struct { const char *setup, *tail; } charset_parser_reference[] = {\n')
count = 0
for name, case in cases.items():
    _, _, nrc, utf, _ = name.split('-')
    if (nrc,utf) not in [('nrc0','utf0'),('nrc1','utf1')]:
        continue
    sequence = bytes.fromhex(case['sequence_hex'])
    setup, separator, _ = sequence.partition(b'\x1b[1;1H')
    assert separator
    reply = bytes.fromhex(case['reply_hex'])
    tail = reply[reply.index(b'\x1bP1$u'):]
    out += '    {'+literal(setup)+','+literal(tail)+'}, /* '+name+' */\n'
    count += 1
assert count == 160
(root/'tests/charset_parser_reference.h').write_text(out+'};\n', newline='\n')
print(count)
