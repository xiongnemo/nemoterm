"""Generate compact read-only ISO 2022 tables from pinned XTerm mapping data.

This development tool needs the two explicitly supplied source files; the
terminal does not depend on Python, X11, or the reference XTerm at runtime.
"""
import argparse,hashlib,re
from pathlib import Path

TABLES=['NRCS_Dutch','NRCS_Finnish','NRCS_French','NRCS_French_Canadian','NRCS_German',
 'NRCS_Italian','NRCS_Norwegian_Danish','NRCS_Portuguese','NRCS_Spanish','NRCS_Swedish',
 'NRCS_Swiss','NRCS_Greek','NRCS_Hebrew','NRCS_Russian','NRCS_Serbo_Croatian','NRCS_Turkish',
 'DEC_Supp_Graphic','DEC_Technical','DEC_Cyrillic','DEC_Greek_Supp','DEC_Hebrew_Supp',
 'DEC_Turkish_Supp','JIS_Roman','JIS_Katakana','ISO_Greek_Supp','ISO_Hebrew','ISO_Latin_2',
 'ISO_Latin_5','ISO_Latin_Cyrillic','DEC_Spec_Graphic']

def generate(source,keys):
    assert hashlib.sha256(source.read_bytes()).hexdigest()=='a6c3be7bb162c771a73108a57522ea7af33e7539d1474384ddc5cd6204dc10b6'
    assert hashlib.sha256(keys.read_bytes()).hexdigest()=='4ba0724695c817a08b4ea3a79c5e8a52e0798cc8d5906281b10f89dc6225208d'
    text=source.read_text();lines=text.splitlines()
    symbols={k:int(v,16) for k,v in re.findall(r'^#define\s+(XK_\w+)\s+0x([0-9a-fA-F]+)',keys.read_text(),re.M)}
    tables={};input_masks={}
    for name in TABLES:
        start=next(i for i,l in enumerate(lines) if l.startswith('#define map_'+name+'('))
        # DEC Supplemental leaves unspecified positions as the original byte,
        # whereas the other table macros start from the seven-bit position.
        data=([0xffff]*96 if name=='DEC_Supp_Graphic' else list(range(0x20,0x80)));seen=set()
        masks={'MAP':[0,0,0],'UNI':[0,0,0]}
        for line in lines[start+1:]:
            if match:=re.search(r'\b(MAP|UNI|XXX)\((.*?)\)\s*(?:/\*|\\|$)',line):
                operation=match[1]
                left,right=map(str.strip,match[2].split(',',1));position=int(left,16)
                assert 0x20<=position<=0x7f and position not in seen,(name,line)
                seen.add(position)
                if right in symbols:value=symbols[right]
                elif right=='UNDEF':value=0x2426
                elif right.startswith('PUA('):value=0xeeee+int(right[4:-1],0)
                else:value=int(right,0)
                assert 0<=value<=0xffff and not 0xd800<=value<=0xdfff,(name,right)
                data[position-0x20]=value
                if operation in masks:
                    bit=position-0x20
                    masks[operation][bit//32] |= 1<<(bit%32)
            if not line.endswith('\\'):break
        assert seen,name
        # xtermCharSetOut handles the DEC special underscore outside the macro.
        if name=='DEC_Spec_Graphic':data[0x5f-0x20]=0
        tables[name]=data
        input_masks[name]=masks
    # Carry the complete upstream notice alongside the derived data.
    notice=text[text.index('/*\n * Copyright'):text.index('#ifndef included_charsets_h')]
    output='/* Generated by tools/generate_charset_tables.py; do not edit. */\n'+notice
    output+='/* XTerm charsets.h v1.36, xterm-412; pinned input hashes in generator. */\n'
    for name,data in tables.items():
        output+='static const uint16_t charset_'+name+'[96] = {\n'
        for i in range(0,96,12):output+='    '+', '.join(f'0x{x:04x}' for x in data[i:i+12])+',\n'
        output+='};\n\n'
    output+='/* Reverse mappings include explicit MAP/UNI entries only; XXX entries\n'
    output+=' * deliberately have no input mapping in xtermCharSetIn. */\n'
    output+='static const struct { const uint16_t *mapping; uint32_t direct[3], unicode[3]; }\n'
    output+='charset_input_masks[] = {\n'
    for name,masks in input_masks.items():
        output+='    {charset_'+name+', {'+','.join(f'0x{x:08x}' for x in masks['MAP'])+'}, {'
        output+=','.join(f'0x{x:08x}' for x in masks['UNI'])+'}},\n'
    output+='};\n'
    return output

if __name__=='__main__':
    parser=argparse.ArgumentParser(description=__doc__)
    parser.add_argument('xterm_header',type=Path);parser.add_argument('keysym_header',type=Path)
    parser.add_argument('--output',type=Path,default=Path('vendor/putty-0.85/terminal/nemo_charset_data.h'))
    args=parser.parse_args();args.output.write_text(generate(args.xterm_header,args.keysym_header),encoding='utf-8',newline='\n')
