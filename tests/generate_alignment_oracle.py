"""Generate DECALN expectations from the retained independent XTerm capture."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
raw = gzip.decompress((root/'research/alignment-audit-evidence/xterm.json.gz').read_bytes())
manifest = json.loads((root/'research/alignment-audit-validation.json').read_text(encoding='utf-8'))
record = next(v for v in manifest['files'] if v['path'].endswith('/xterm.json.gz'))
assert hashlib.sha256(raw).hexdigest() == record['raw_sha256']
source = json.loads(raw)


def literal(text):
    return '"' + ''.join('\\%03o' % byte if byte < 32 or byte >= 127 else
        '\\' + chr(byte) if chr(byte) in '\\"' else chr(byte)
        for byte in text.encode()) + '"'


cases = []
for name, case in source['cases'].items():
    # XTerm clears its RGB flags but keeps packed RGB values, reporting them
    # as indexed colours after DECALN. Keep valid RGB storage/reporting here;
    # this known difference has a separate direct regression assertion.
    if name == 'rgb':
        continue
    assert case['reply'].encode().hex() == case['reply_hex']
    cases.append((name, case['sequence'], case['reply']))
assert len(cases) == 13
header = '/* Generated by tests/generate_alignment_oracle.py from '+source['version']+'. */\n'
header += 'static const struct { const char *name, *sequence, *reply; } alignment_oracle[] = {\n'
header += ''.join('    {'+', '.join(map(literal, case))+'},\n' for case in cases)+'};\n'
native = '# Generated by tests/generate_alignment_oracle.py.\nCASES = [\n'
native += ''.join('    '+repr(case)+',\n' for case in cases)+']\n'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name, text in [('alignment_oracle_cases.h', header), ('alignment_oracle_cases.py', native)]:
    target = root/'tests'/name
    if args.check:
        assert target.read_text(encoding='utf-8') == text, 'Regenerate '+name
    else:
        target.write_text(text, encoding='utf-8', newline='\n')
