"""Generate only environment-independent XTSMGRAPHICS reference expectations."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'research/graphics-query-xterm.json').read_text(encoding='utf-8'))
# These values depend on implementation limits, resource defaults or geometry.
# Missing Pi is also represented differently (xterm emits its -1 sentinel as
# 65535; Nemoterm consistently treats an omitted numeric parameter as zero).
separate = {'1;4;0', '1;2;0', '1;3;257', '1;3;1024', '2;1;0', '2;4;0', ';1;0'}


def literal(text):
    return '"'+''.join('\\%03o'%b if b < 32 or b >= 127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode())+'"'


cases = [(n, c['sequence'], c['reply']) for n, c in source['cases'].items() if n not in separate]
outputs = {
    'graphics_query_oracle_cases.h': '/* Generated by tests/generate_graphics_query_oracle.py. */\n' +
        'static const struct { const char *name, *sequence, *reply; } graphics_query_oracle[] = {\n'+
        ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in cases)+'};\n',
    'graphics_query_oracle_cases.py': '# Generated by tests/generate_graphics_query_oracle.py.\nCASES = [\n'+
        ''.join('    '+repr(c)+',\n' for c in cases)+']\n',
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name, content in outputs.items():
    path = root/'tests'/name
    if args.check:
        assert path.read_text(encoding='utf-8') == content, 'Regenerate '+name
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
