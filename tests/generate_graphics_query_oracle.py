"""Generate only environment-independent XTSMGRAPHICS reference expectations."""
import argparse
import hashlib
import io
import json
from zipfile import ZipFile
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'testdata/upstream/graphics-query-xterm.json').read_text(encoding='utf-8'))
# These values depend on implementation limits, resource defaults or geometry.
# Missing Pi is also represented differently (xterm emits its -1 sentinel as
# 65535; Nemoterm consistently treats an omitted numeric parameter as zero).
separate = {'1;4;0', '1;2;0', '1;3;257', '1;3;1024', '2;1;0', '2;4;0', ';1;0'}


def literal(text):
    return '"'+''.join('\\%03o'%b if b < 32 or b >= 127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode())+'"'


# The original XTerm lacked the optional ReGIS decoder. Preserve it as
# the reference for other items; use identical Pi=3 requests sent to the
# pinned ReGIS-enabled build at the product's actual default geometry.
archive = (root/'testdata/upstream/regis-discovery-xterm.zip').read_bytes()
assert hashlib.sha256(archive).hexdigest() == '873bcd56b1dd5ab0fff77b39185632c6686459b9b94af369d276fd8646e3c839'
with ZipFile(io.BytesIO(archive)) as z:
    enabled = json.loads(z.read('800x480.json'))['cases']
cases = []
for name, case in source['cases'].items():
    if name in separate:
        continue
    if name.startswith('3;'):
        assert enabled[name]['sequence'] == case['sequence']
        case = enabled[name]
    cases.append((name, case['sequence'], case['reply']))
for name, case in enabled.items():
    if (name.startswith('3;') and name not in source['cases']) or name == 'invalid-arity':
        cases.append(('regis-'+name, case['sequence'], case['reply']))
outputs = {
    'graphics_query_oracle_cases.h': '/* Generated by tests/generate_graphics_query_oracle.py. */\n' +
        'static const struct { const char *name, *sequence, *reply; } graphics_query_oracle[] = {\n'+
        ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in cases)+'};\n',
    'graphics_query_oracle_cases.py': '# Generated by tests/generate_graphics_query_oracle.py.\nCASES = [\n'+
        ''.join('    '+repr(c)+',\n' for c in cases)+']\n',
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name, content in outputs.items():
    path = root/'tests'/name
    if args.check:
        assert path.read_text(encoding='utf-8') == content, 'Regenerate '+name
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
