"""Generate unchanged reference replies for presentation-state tests."""
import argparse
import json
from pathlib import Path
from presentation_state_direct_cases import CASES as direct

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'research/presentation-state-xterm.json').read_text(encoding='utf-8'))
separate = {f'charset-{bank}U': 'PuTTY SCO alternate charset is supported and reported as U.'
            for bank in ('(', ')', '*', '+')}
separate['retained-modern'] = 'Equivalent DECRQSS SGR fields use the established Nemoterm ordering.'
separate['cancel-1a'] = 'Existing SUB recovery cancels without printing a replacement glyph.'
cases = [(name, item['sequence'], item['reply']) for name,item in source['cases'].items()
         if name not in separate]


def literal(text):
    return '"'+''.join('\\%03o'%b if b < 32 or b >= 127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode())+'"'


outputs = {
    'presentation_state_oracle_cases.h': '/* Generated by tests/generate_presentation_state_oracle.py. */\n'+
        'static const struct { const char *name, *sequence, *reply; } presentation_state_oracle[] = {\n'+
        ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in cases)+'};\n'+
        'static const struct { const char *name, *sequence, *reply; } presentation_state_direct[] = {\n'+
        ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in direct)+'};\n',
    'presentation_state_oracle_cases.py': '# Generated by tests/generate_presentation_state_oracle.py.\nCASES = [\n'+
        ''.join('    '+repr(c)+',\n' for c in cases)+']\n',
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name, content in outputs.items():
    path = root/'tests'/name
    if args.check: assert path.read_text(encoding='utf-8') == content, 'Regenerate '+name
    else: path.write_text(content, encoding='utf-8')
