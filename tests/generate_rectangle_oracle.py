"""Regenerate C expectations solely from the independently captured XTerm JSON."""
import json,re
from pathlib import Path
root=Path(__file__).resolve().parent.parent
source=json.loads((root/'research/rectangle-xterm.json').read_text(encoding='utf-8'))
flags={1:'ATTR_BOLD',2:'ATTR_DIM',3:'ATTR_ITALIC',4:'ATTR_UNDER',5:'ATTR_BLINK',7:'ATTR_REVERSE',8:'ATTR_CONCEAL',9:'ATTR_STRIKE'}
q='\x1b[6n\x1bP$q*x\x1b\\\x1b[?6l\x1b[31#y'
def literal(s):
    return '"'+''.join('\\%03o'%b if b<32 or b>=127 else '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in s.encode())+'"'
lines=['/* Generated by tests/generate_rectangle_oracle.py from '+source['version']+'. */',
       'static const struct { const char *name, *sequence; unsigned chars[60], attrs[60]; } rectangle_oracle[] = {']
for name,case in source['cases'].items():
    if name=='copy-combining-wide':continue # tested as original Unicode plus combining chains
    seq=case['sequence'].rsplit(q,1)[0]
    chars=','.join(str(v['checksum']) for v in case['cells'])
    attrs=','.join('|'.join(flags[n] for n in map(int,v['sgr'].split(';')) if n in flags) or '0' for v in case['cells'])
    lines.append('  {'+literal(name)+','+literal(seq)+',{'+chars+'},{'+attrs+'}},')
lines.append('};')
(root/'tests/rectangle_oracle_cases.h').write_text('\n'.join(lines)+'\n', encoding='utf-8', newline='\n')
