"""Generate checksum fixtures from unchanged XTerm wire captures."""
import argparse
import json
from pathlib import Path
from checksum_direct_cases import CASES as direct

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'research/checksum-xterm.json').read_text(encoding='utf-8'))
separate = {'args-;1;1;1;1;4': 'Empty numeric identifier is zero, consistently with other Nemoterm queries.'}
for mode in range(32):
    separate[f'mode-{mode}-combining'] = 'Retained decomposed scalars; xterm composes some base/mark sequences.'
    if mode < 16:
        separate[f'mode-{mode}-unicode'] = 'xterm legacy charSeen values depend on preceding writes; see ordering probe.'
        separate[f'mode-{mode}-uk'] = 'PuTTY UTF-8 ignores the British national charset, retaining ASCII #.'
cases = [(name, c['sequence'], c['reply']) for name, c in source['cases'].items()
         if name not in separate]


def literal(text):
    return '"'+''.join('\\%03o'%b if b < 32 or b >= 127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode())+'"'


outputs = {
    'checksum_oracle_cases.h': '/* Generated by tests/generate_checksum_oracle.py. */\n'+
        'static const struct { const char *name, *sequence, *reply; } checksum_oracle[] = {\n'+
        ''.join('    {'+', '.join(map(literal, c))+'},\n' for c in cases)+'};\n'+
        'static const struct { const char *name, *sequence, *reply; } checksum_direct[] = {\n'+
        ''.join('    {'+', '.join(map(literal, c))+'},\n' for c in direct)+'};\n',
    'checksum_oracle_cases.py': '# Generated by tests/generate_checksum_oracle.py.\nCASES = [\n'+
        ''.join('    '+repr(c)+',\n' for c in cases)+']\n',
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name, content in outputs.items():
    path = root/'tests'/name
    if args.check:
        assert path.read_text(encoding='utf-8') == content, 'Regenerate '+name
    else:
        path.write_text(content, encoding='utf-8')
