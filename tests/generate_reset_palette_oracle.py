"""Generate exact reset/reverse-colour cases from an independent XTerm capture."""
import argparse
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
raw = (root/'research/protocol-reference-evidence/20261114-reset-palette-xterm.json').read_bytes()
source = json.loads(raw)
assert source['version'] == 'XTerm(412)'
assert source['executable_sha256'] == '9f440380b493c91dbd1fcb8a6277df1ca121390b23fe526baa24c15525f4df64'
cases = []
for name, case in source['cases'].items():
    assert case['reply'].encode().hex() == case['reply_hex'], name
    cases.append((name, case['sequence'], case['reply']))
assert len(cases) == 25


def literal(text):
    return '"'+''.join('\\%03o'%b if b < 32 or b >= 127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode())+'"'


provenance = 'Captured XTerm(412), SHA256 '+hashlib.sha256(raw).hexdigest()
outputs = {
    'reset_palette_oracle_cases.h':
        '/* Generated by tests/generate_reset_palette_oracle.py.\n * '+provenance+' */\n'+
        'static const struct { const char *name, *sequence, *reply; } reset_palette_oracle[] = {\n'+
        ''.join('    {'+', '.join(map(literal, case))+'},\n' for case in cases)+'};\n',
    'reset_palette_oracle_cases.py':
        '# Generated by tests/generate_reset_palette_oracle.py.\n# '+provenance+'\nCASES = [\n'+
        ''.join('    '+repr(case)+',\n' for case in cases)+']\n',
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name, content in outputs.items():
    path = root/'tests'/name
    if args.check:
        assert path.read_text(encoding='utf-8') == content, 'Regenerate '+name
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
print(f'{len(cases)} captured XTerm reset/reverse-colour cases')
