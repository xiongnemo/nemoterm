"""Generate reference expectations, keeping invalid reference coordinates explicit."""
import argparse
import json
from pathlib import Path
from reverse_wrap_direct_cases import CASES as DIRECT

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'research/reverse-wrap-xterm.json').read_text(encoding='utf-8'))
EXCLUDED = {f'{mode}-margin-{case}' for mode in ('extended','both')
            for case in ('1-1-bs','1-1-cub7','1-1-cub25','2-5-cub7','2-5-cub25')}


def literal(text):
    return '"'+''.join('\\%03o'%b if b < 32 or b >= 127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode())+'"'


cases = [(n,c) for n,c in source['cases'].items() if n not in EXCLUDED]
outputs = {
    'reverse_wrap_oracle_cases.h': '/* Generated by tests/generate_reverse_wrap_oracle.py. */\n'+
        'static const unsigned reverse_wrap_cells[][2] = {'+','.join('{%d,%d}'%tuple(p) for p in source['cell_positions'])+'};\n'+
        'static const struct { const char *name, *sequence, *reply; unsigned cells[%d]; } reverse_wrap_oracle[] = {\n'%len(source['cell_positions'])+
        ''.join('    {'+', '.join(map(literal,[n,c['input'],c['state_reply']]))+', {'+
                ','.join(map(str,c['cells']))+'}},\n' for n,c in cases)+'};\n'+
        'static const struct { const char *name, *sequence, *reply; } reverse_wrap_direct[] = {\n'+
        ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in DIRECT)+'};\n',
    'reverse_wrap_oracle_cases.py': '# Generated by tests/generate_reverse_wrap_oracle.py.\nCASES = [\n'+
        ''.join('    '+repr((n,c['sequence'],c['reply']))+',\n' for n,c in cases)+']\n',
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name,content in outputs.items():
    path = root/'tests'/name
    if args.check: assert path.read_text(encoding='utf-8') == content, 'Regenerate '+name
    else: path.write_text(content,encoding='utf-8')
