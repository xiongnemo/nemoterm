"""Generate tabulation expectations from the independent XTerm capture."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'research/tabulation-xterm.json').read_text())


def literal(text):
    return '"' + ''.join('\\%03o' % byte if byte < 32 or byte >= 127 else
        '\\' + chr(byte) if chr(byte) in '\\"' else chr(byte)
        for byte in text.encode()) + '"'


lines = ['/* Generated by tests/generate_tabulation_oracle.py from ' + source['version'] + '. */',
         'static const struct { const char *name, *sequence, *reply; } tabulation_oracle[] = {']
cases = []
for name, case in source['cases'].items():
    # Nemoterm consistently ignores unsupported colon subparameters. XTerm
    # discards those parameters and still executes the command's default.
    if ':' in name:
        continue
    # Existing double-width text output wraps at the physical rather than
    # logical row edge. Track these three failures separately; cursor-only
    # double-width tabulation is still compared above.
    if name.endswith('-double-wrap'):
        continue
    cases.append((name, case['sequence'], case['reply']))
    lines.append('    {' + ', '.join(map(literal, [name, case['sequence'], case['reply']])) + '},')
lines.append('};')
text = '\n'.join(lines) + '\n'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
target = root/'tests/tabulation_oracle_cases.h'
native = '# Generated by tests/generate_tabulation_oracle.py.\nCASES = [\n' + \
    ''.join('    ' + repr(case) + ',\n' for case in cases) + ']\n'
for target, content in [(target, text), (root/'tests/tabulation_oracle_cases.py', native)]:
    if args.check:
        assert target.read_text() == content, 'Regenerate ' + target.name
    else:
        target.write_text(content)
