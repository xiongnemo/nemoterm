"""Generate independent double-size cursor and cell expectations."""
import argparse
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'research/double-size-xterm.json').read_text(encoding='utf-8'))


def literal(text):
    return '"' + ''.join('\\%03o' % b if b < 32 or b >= 127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode()) + '"'


lines = ['/* Generated by tests/generate_double_size_oracle.py from XTerm(412). */',
    'static const struct { const char *name, *sequence, *reply; unsigned cells[27]; } double_size_oracle[] = {']
native = []
for name, case in source['cases'].items():
    # XTerm dotext computes real_rmargin before WrapLine and uses that stale
    # width for the first output run on the next (single-width) line. A direct
    # assertion instead requires the destination row's own logical width.
    if name.endswith('-ascii-next-normal'):
        continue
    lines.append('    {' + ', '.join(map(literal, [name, case['input'], case['cursor_reply']])) +
        ', {' + ','.join(str(c['checksum']) for c in case['cells']) + '}},')
    native.append((name, case['input'], case['cursor_reply']))
lines.append('};')
outputs = {
    'double_size_oracle_cases.h': '\n'.join(lines)+'\n',
    'double_size_oracle_cases.py': '# Generated by tests/generate_double_size_oracle.py.\nCASES = [\n' +
        ''.join('    '+repr(case)+',\n' for case in native) + ']\n',
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name, content in outputs.items():
    path = root/'tests'/name
    if args.check:
        assert path.read_text(encoding='utf-8') == content, 'Regenerate '+name
    else:
        path.write_text(content, encoding='utf-8', newline='\n')
