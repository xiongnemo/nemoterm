"""Retain raw C1 reply bytes; palette and title policy are separate checks."""
import argparse,json
from pathlib import Path
root=Path(__file__).resolve().parents[1]
source=json.loads((root/'research/c1-controls-xterm.json').read_text(encoding='utf-8'))
separate={'reply-palette-bel','reply-palette-st','reply-title'}
cases=[(name,c['sequence'],bytes.fromhex(c['reply_hex'])) for name,c in source['cases'].items() if name not in separate]
def literal(data):
    if isinstance(data,str):data=data.encode('utf-8')
    return '"'+''.join('\\%03o'%b if b<32 or b>=127 else '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in data)+'"'
outputs={'c1_controls_oracle_cases.h':'/* Generated by tests/generate_c1_controls_oracle.py. */\n'+
    'static const struct { const char *name, *sequence, *reply; } c1_controls_oracle[] = {\n'+
    ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in cases)+'};\n',
    'c1_controls_oracle_cases.py':'# Generated by tests/generate_c1_controls_oracle.py.\nCASES = [\n'+
    ''.join('    '+repr(c)+',\n' for c in cases)+']\n'}
parser=argparse.ArgumentParser();parser.add_argument('--check',action='store_true');args=parser.parse_args()
for name,value in outputs.items():
    path=root/'tests'/name
    if args.check:assert path.read_text(encoding='utf-8')==value,name
    else:path.write_text(value,encoding='utf-8',newline='\n')
print('Exact byte cases:',len(cases))
