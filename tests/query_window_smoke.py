"""Verify cursor pixels, status queries and keyboard capabilities through ConPTY."""
import frida
from underline_capabilities import PROGRAMS, cases as underline_cases, decode_reply

from native_test_utils import (root, c, w, u, k, hashlib, json, os, subprocess,
    sys, tempfile, Path, threading, time, read_snapshot, write_snapshot,
    memory_sample, wait_for, find_window, capture)

u.GetClientRect.argtypes = [w.HWND, c.POINTER(w.RECT)]
u.GetForegroundWindow.restype = w.HWND
u.GetCaretBlinkTime.restype = w.UINT

with tempfile.TemporaryDirectory(prefix='nemoterm-query-') as directory:
    directory = Path(directory)
    report, control = directory/'report.json', directory/'control.json'
    process = subprocess.Popen([str(root/'dist/nemoterm.exe'), '--cols', '40', '--rows', '12',
        '-e', sys.executable, str(root/'tests/mouse_fixture.py'), str(report), str(control)],
        env=dict(os.environ, NEMOTERM_CONPTY='bundled'), creationflags=subprocess.CREATE_NO_WINDOW)
    handle = k.OpenProcess(0x410, False, process.pid)
    samples, stop = [], threading.Event()
    evidence = dict(focus_model='owned-process instrumented active and inactive states',
                    executable_sha256=hashlib.sha256((root/'dist/nemoterm.exe').read_bytes()).hexdigest())
    session = script = hwnd = None
    completed = False
    def sampler():
        while not stop.is_set():
            samples.append(memory_sample(handle))
            stop.wait(0.025)
    worker = threading.Thread(target=sampler, daemon=True)
    worker.start()
    def current():
        value = read_snapshot(report)
        assert not value.get('error') and process.poll() is None, value
        return value
    def snapshot_when(predicate):
        # A sharing violation may yield an empty read. Keep the exact snapshot
        # that satisfied the predicate instead of reopening the mailbox.
        def probe():
            value = current()
            return value if predicate(value) else None
        return wait_for(probe)
    def phase(name, sequence, expected):
        write_snapshot(control, {'phase':name, 'sequence':sequence})
        try:
            observed = snapshot_when(lambda value: value.get('phase') == name and
                     'hex' in value and expected in bytes.fromhex(value['hex']))
        except AssertionError:
            raise AssertionError((name, expected, current()))
        time.sleep(0.08)
        pixels = capture(hwnd, return_pixels=True)
        evidence[name] = dict(reply=observed['hex'], sha256=hashlib.sha256(pixels).hexdigest(),
                              desktop_foreground=int(u.GetForegroundWindow() or 0))
        return pixels
    def cursor_shape(pixels):
        rect = w.RECT()
        u.GetClientRect(hwnd, c.byref(rect))
        indices = [i//3 for i in range(0, len(pixels), 3) if pixels[i:i+3] == b'\xff\0\0']
        if not indices: return [0, 0, 0]
        xs, ys = [i%rect.right for i in indices], [i//rect.right for i in indices]
        return [max(xs)-min(xs)+1, max(ys)-min(ys)+1, len(indices)]
    def identity_phase(name, sequence, expected):
        # A final DSR is a stream barrier. Compare all bytes, including any
        # duplicate reply accidentally generated by the console host.
        expected += b'\x1b[0n'
        write_snapshot(control, {'phase':name, 'sequence':sequence+'\x1b[5n'})
        observed = snapshot_when(lambda value: value.get('phase') == name and
                                 bytes.fromhex(value.get('hex', '')).endswith(b'\x1b[0n'))
        assert bytes.fromhex(observed['hex']) == expected, (name, observed, expected)
        evidence[name] = dict(sequence=sequence, reply=observed['hex'])
    try:
        hwnd = wait_for(lambda: find_window(process.pid))
        wait_for(current)
        session = frida.attach(process.pid)
        script = session.create_script((root/'tests/query_focus_probe.js').read_text())
        script.load()
        script.exports_sync.set_focus(hex(hwnd), True)
        for prefix, final, reply in [('', 'c', b'\x1b[?62;4;22c'),
                ('>', 'c', b'\x1b[>0;136;0c'), ('=', 'c', b'\x1bP!|00000000\x1b\\'),
                ('>', 'q', b'\x1bP>|Nemoterm(PuTTY 0.85)\x1b\\')]:
            valid_args = ('', '0', '0;9', ';9', '0:0', '0:1', ':1', '0;1:2', '0:0:0', '1:0', '1;0:0')
            for arg in (*valid_args, '1', '2', '1;0', '999999999999999999999'):
                expected = reply if arg in valid_args else b''
                identity_phase(f'identity-{prefix}{final}-{arg}', f'\x1b[{prefix}{arg}{final}', expected)
        identity_phase('identity-cursor-visible', '\x1b[?25h\x1b[=c\x1b[?25$p',
                       b'\x1bP!|00000000\x1b\\\x1b[?25;1$y')
        identity_phase('identity-cursor-hidden', '\x1b[?25l\x1b[=c\x1b[=1c\x1b[=2c\x1b[?25$p',
                       b'\x1bP!|00000000\x1b\\\x1b[?25;2$y')
        identity_phase('identity-sco-cursor', '\x1b[?25h\x1b[42"p\x1b[=c\x1b[41"p\x1b[?25$p',
                       b'\x1b[?25;2$y')
        identity_phase('identity-alt', '\x1b[?1049h\x1b[=c\x1b[>q\x1b[?1049l',
                       b'\x1bP!|00000000\x1b\\\x1bP>|Nemoterm(PuTTY 0.85)\x1b\\')
        blank = phase('hidden', '\x1b[0m\x1b[2 q\x1b[?25l\x1b[2J\x1b[2;2H'
            '\x1b]10;rgb:f/f/f\x07\x1b]11;rgb:0/0/0\x07\x1b]12;rgb:f/0/0\x07'
            '\x1bP$q q\x1b\\', b'\x1bP1$r2 q\x1b\\')
        shapes = []
        for style, name in [(2, 'block'), (4, 'underline'), (6, 'bar')]:
            pixels = phase(name, f'\x1b[?25h\x1b[{style} q\x1bP$q q\x1b\\',
                           f'\x1bP1$r{style} q\x1b\\'.encode())
            shape = cursor_shape(pixels)
            shapes.append(shape)
            evidence[name]['shape'] = shape
            capture(hwnd, 'cursor-'+name+'.png')
        assert shapes[0][0] > 1 and shapes[0][1] > 1, shapes
        assert shapes[1][0] > 1 and shapes[1][1] == 1, shapes
        assert shapes[2][0] == 1 and shapes[2][1] > 1, shapes
        before_identity = capture(hwnd, return_pixels=True)
        identity_phase('identity-visible-pixels', '\x1b[=c\x1b[>q',
                       b'\x1bP!|00000000\x1b\\\x1bP>|Nemoterm(PuTTY 0.85)\x1b\\')
        time.sleep(.08)
        after_identity = capture(hwnd, return_pixels=True)
        assert after_identity == before_identity, 'identity request changed cursor pixels'
        evidence['identity-visible-pixels']['sha256'] = hashlib.sha256(after_identity).hexdigest()
        hidden = phase('hidden-again', '\x1b[?25l\x1bP$q q\x1b\\', b'\x1bP1$r6 q\x1b\\')
        assert hidden == blank, 'cursor left stale pixels when hidden'
        phase('sgr', '\x1b[31;44m\x1bP$qm\x1b\\', b'\x1bP1$r0;31;44m\x1b\\')
        phase('margins', '\x1b[3;10r\x1bP$qr\x1b\\', b'\x1bP1$r3;10r\x1b\\')
        phase('unsupported', '\x1bP$qfuture-query\x1b\\', b'\x1bP0$r\x1b\\')
        phase('geometry', '\x1bP$q$|\x1b\\\x1bP$q*|\x1b\\',
              b'\x1bP1$r40$|\x1b\\\x1bP1$r12*|\x1b\\')
        assert u.MoveWindow(hwnd, 30, 30, 650, 470, True)
        dimensions = snapshot_when(lambda value: value.get('columns', 40) != 40)
        expected = f"\x1bP1$r{dimensions['columns']}$|\x1b\\\x1bP1$r{dimensions['rows']}*|\x1b\\"
        phase('geometry-after-resize', '\x1bP$q$|\x1b\\\x1bP$q*|\x1b\\', expected.encode())

        phase('blink', '\x1b[0m\x1b[r\x1b[2J\x1b[2;2H\x1b[?25h\x1b[1 q\x1bP$q q\x1b\\',
              b'\x1bP1$r1 q\x1b\\')
        blink_ms = u.GetCaretBlinkTime()
        if 0 < blink_ms <= 1000:
            states = set()
            deadline = time.monotonic()+2.5*blink_ms/1000
            while time.monotonic() < deadline:
                states.add(cursor_shape(capture(hwnd, return_pixels=True))[2] > 0)
                time.sleep(0.06)
            evidence['blink_states'] = sorted(states)
            assert states == {False, True}, evidence
        else:
            evidence['blink_pixel_check_skipped'] = 'System blink disabled or slow'
        steady = phase('blink-off', '\x1b[?12l\x1b[?12$p\x1bP$q q\x1b\\',
              b'\x1b[?12;2$y\x1bP1$r2 q\x1b\\')
        if 0 < blink_ms <= 1000:
            states = set()
            deadline = time.monotonic()+2.5*blink_ms/1000
            while time.monotonic() < deadline:
                states.add(cursor_shape(capture(hwnd, return_pixels=True))[2] > 0)
                time.sleep(0.06)
            evidence['steady_states'] = sorted(states)
            assert states == {True}, evidence
        frozen = phase('frozen-query', '\x1b[?2026h\x1b[6 q\x1bP$q q\x1b\\',
                       b'\x1bP1$r6 q\x1b\\')
        assert frozen == steady, 'cursor change escaped synchronized presentation'
        released = phase('released-query', '\x1b[?2026l\x1bP$q q\x1b\\',
                         b'\x1bP1$r6 q\x1b\\')
        # A parser reply can precede deferred presentation. Require the exact
        # final bar geometry within less than the synchronized-update timeout.
        released = wait_for(lambda: pixels
                            if cursor_shape(pixels := capture(hwnd, return_pixels=True))[:2] == shapes[2][:2]
                            else None, timeout=.8)
        released_shape = cursor_shape(released)
        if released_shape[:2] != shapes[2][:2]:
            capture(hwnd, '../build/query-released-failed.png')
        assert released_shape[:2] == shapes[2][:2], (shapes, released_shape, evidence)
        script.exports_sync.set_focus(hex(hwnd), False)
        passive = wait_for(lambda: pixels if (pixels := capture(hwnd, return_pixels=True)) != released else None)
        passive_shape = cursor_shape(passive)
        assert passive_shape[0] == 1 and 0 < passive_shape[2] < released_shape[2], passive_shape
        evidence['inactive-cursor'] = dict(shape=passive_shape, sha256=hashlib.sha256(passive).hexdigest())
        script.exports_sync.set_focus(hex(hwnd), True)
        wait_for(lambda: capture(hwnd, return_pixels=True) == released)
        # Inject messages only into our own HWND. This exercises the real
        # Win32 translator; modifier combinations are tested by test_tcap.
        # Query values must match both the protocol oracle and the child input.
        keys = [('kf1', 0x70, b'\x1bOP', False), ('kf12', 0x7b, b'\x1b[24~', False),
                ('kf13', 0x7c, b'\x1b[25~', False), ('kf24', 0x87, b'\x1b[45~', False),
                ('khome', 0x24, b'\x1b[H', True), ('kend', 0x23, b'\x1b[F', True),
                ('kcuu1', 0x26, b'\x1b[A', True), ('kcud1', 0x28, b'\x1b[B', True),
                ('kcuf1', 0x27, b'\x1b[C', True), ('kcub1', 0x25, b'\x1b[D', True),
                ('kich1', 0x2d, b'\x1b[2~', True), ('kdch1', 0x2e, b'\x1b[3~', True),
                ('kpp', 0x21, b'\x1b[5~', True), ('knp', 0x22, b'\x1b[6~', True),
                ('kbs', 0x08, b'\x7f', False)]
        encoded_names = ';'.join(name.encode().hex() for name, *_ in keys)
        for app in (False, True):
            values = [value.replace(b'\x1b[', b'\x1bO')
                      if app and name in ('khome', 'kend', 'kcuu1', 'kcud1', 'kcuf1', 'kcub1')
                      else value for name, _, value, _ in keys]
            expected = b'\x1bP1+r'+b';'.join(name.encode().hex().encode()+b'='+value.hex().encode()
                for (name, *_), value in zip(keys, values))+b'\x1b\\'
            name = 'keys-application' if app else 'keys-normal'
            phase(name, f'\x1b[?1{"h" if app else "l"}\x1bP+q{encoded_names}\x1b\\', expected)
            for _, vk, _, extended in keys:
                flags = 1 | (u.MapVirtualKeyW(vk, 0) << 16) | (int(extended) << 24)
                u.SendMessageW(hwnd, 0x100, vk, flags)
                u.SendMessageW(hwnd, 0x101, vk, flags | 0xc0000000)
            expected_input = expected+b''.join(values)
            try:
                observed = snapshot_when(lambda value:
                    bytes.fromhex(value.get('hex', '')) == expected_input)
            except AssertionError:
                raise AssertionError((name, expected_input.hex(), current()))
            evidence[name].update(key_input=b''.join(values).hex(), child_input=observed['hex'])
        phase('tcap-colours', '\x1bP+q436f;544e;524742\x1b\\',
              b'\x1bP1+r436f=323536;544e=787465726d2d323536636f6c6f72;524742=38\x1b\\')
        phase('tcap-unsupported', '\x1bP+q637570\x1b\\', b'\x1bP0+r\x1b\\')
        # Exact wire replies for the parameter-free rendition whitelist.
        # Replay the values actually returned by the terminal, then use a
        # separate DECRQSS query to check their effect through real ConPTY.
        renditions = {'smul': '\x1b[4m', 'rmul': '\x1b[24m',
            'us': '\x1b[4m', 'ue': '\x1b[24m',
            'sitm': '\x1b[3m', 'ritm': '\x1b[23m',
            'ZH': '\x1b[3m', 'ZR': '\x1b[23m',
            'smxx': '\x1b[9m', 'rmxx': '\x1b[29m',
            'Smol': '\x1b[53m', 'Rmol': '\x1b[55m'}
        returned = {}
        for name, value in renditions.items():
            encoded = name.encode().hex()
            case = 'tcap-rendition-'+name
            identity_phase(case, f'\x1bP+q{encoded}\x1b\\',
                           f'\x1bP1+r{encoded}={value.encode().hex()}\x1b\\'.encode())
            reply = bytes.fromhex(evidence[case]['reply'])
            returned[name] = bytes.fromhex(reply.split(b'=', 1)[1].split(b'\x1b\\', 1)[0].decode()).decode()
        for name in ('smol', 'rmol', 'smulx', 'setulc', 'Su', 'Setulc1'):
            identity_phase('tcap-unknown-'+name, f'\x1bP+q{name.encode().hex()}\x1b\\', b'\x1bP0+r\x1b\\')
        on = ''.join(returned[name] for name in ('sitm', 'smul', 'smxx', 'Smol'))
        identity_phase('tcap-renditions-replay-on', '\x1b[0m'+on+'\x1bP$qm\x1b\\',
                       b'\x1bP1$r0;3;9;4;53m\x1b\\')
        off = ''.join(returned[name] for name in ('ritm', 'rmul', 'rmxx', 'Rmol'))
        identity_phase('tcap-renditions-replay-off', off+'\x1bP$qm\x1b\\', b'\x1bP1$r0m\x1b\\')
        # Capture the real parameter programs for independent ncurses checks.
        # Windows replays numeric expectations here; it does not implement a
        # second evaluator or claim that static literals are tparm expansion.
        for name, value in PROGRAMS.items():
            encoded = name.encode().hex()
            case = 'tcap-program-'+name
            identity_phase(case, f'\x1bP+q{encoded}\x1b\\',
                           f'\x1bP1+r{encoded}={value.hex()}\x1b\\'.encode())
            decode_reply(name, bytes.fromhex(evidence[case]['reply']))
        # A repeated Setulc query exceeds the previous 14 KiB reply bound and
        # crosses many ConPTY pipe reads. Verify all bytes and recovery through
        # the actual host, not just the core parser's in-memory reply buffer.
        token = 'Setulc'.encode().hex()
        many = (token+';')*157
        reply = b'\x1bP1+r'+((token+'='+PROGRAMS['Setulc'].hex()+';')*157).encode()+b'\x1b\\'
        assert len(reply) == 21045
        identity_phase('tcap-program-max', '\x1bP+q'+many+'\x1b\\', reply)
        identity_phase('tcap-program-overflow', '\x1bP+q'+many+token+'\x1b\\', b'\x1bP0+r\x1b\\')
        for name, parameter, sequence, expected in underline_cases():
            identity_phase(f'tcap-expanded-{name}-{parameter}',
                           '\x1b[0m'+sequence.decode()+'\x1bP$qm\x1b\\', expected)
        identity_phase('tcap-expanded-reset', '\x1b[4:3;58:2::18:52:86m\x1b[24;59m\x1bP$qm\x1b\\',
                       b'\x1bP1$r0m\x1b\\')
        evidence.update(peak_private_ws=max(s['private_ws'] for s in samples),
                        peak_total_ws=max(s['total_ws'] for s in samples),
                        executable_sha256=hashlib.sha256((root/'dist/nemoterm.exe').read_bytes()).hexdigest())
        assert evidence['peak_private_ws'] < 20_000_000, evidence
        completed = True
        print('Native cursor pixels, queries and keyboard capabilities passed:', evidence)
    finally:
        evidence['completed'] = completed
        try:
            if script:
                evidence['focus_instrumentation'] = script.exports_sync.stats()
            if not completed and hwnd and process.poll() is None:
                capture(hwnd, 'query-failure.png')
        except Exception as error:
            evidence['diagnostic_error'] = str(error)
        if session:
            try:
                session.detach()
            except frida.InvalidOperationError:
                pass
        (root/'research/query-window-observed.json').write_text(json.dumps(evidence, indent=2))
        stop.set()
        worker.join(2)
        k.CloseHandle(handle)
        write_snapshot(control, {'stop': True})
        process.wait(timeout=10)
