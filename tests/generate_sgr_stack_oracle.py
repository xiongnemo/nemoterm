"""Generate exact rendition-stack fixtures, retaining the raw XTerm capture."""
import argparse
import json
from pathlib import Path
from sgr_stack_direct_cases import CASES as direct

root = Path(__file__).resolve().parents[1]
source = json.loads((root/'research/sgr-stack-xterm.json').read_text(encoding='utf-8'))
separate = {f'underline-{style}-{selector}':
    'Nemoterm supports modern underline substyles which this XTerm ignores.'
    for style in ('4:2','4:3') for selector in ('all','4','4;21')}
cases = [(name, c['sequence'], c['reply']) for name,c in source['cases'].items()
         if name not in separate]


def literal(text):
    return '"'+''.join('\\%03o'%b if b < 32 or b >= 127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode())+'"'


outputs = {
    'sgr_stack_oracle_cases.h': '/* Generated by tests/generate_sgr_stack_oracle.py. */\n'+
        'static const struct { const char *name, *sequence, *reply; } sgr_stack_oracle[] = {\n'+
        ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in cases)+'};\n'+
        'static const struct { const char *name, *sequence, *reply; } sgr_stack_direct[] = {\n'+
        ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in direct)+'};\n',
    'sgr_stack_oracle_cases.py': '# Generated by tests/generate_sgr_stack_oracle.py.\nCASES = [\n'+
        ''.join('    '+repr(c)+',\n' for c in cases)+']\n',
}
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name,content in outputs.items():
    path = root/'tests'/name
    if args.check: assert path.read_text(encoding='utf-8') == content, 'Regenerate '+name
    else: path.write_text(content, encoding='utf-8')
