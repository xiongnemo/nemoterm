"""Generate exact DEC status cases without changing the captured reference."""
import argparse
import json
from pathlib import Path

root=Path(__file__).resolve().parents[1]
source=json.loads((root/'research/dec-status-xterm.json').read_text(encoding='utf-8'))
# Nemoterm does not accept downloadable UDK bindings: report unavailable, not
# xterm's unlocked state. An explicitly empty checksum id is consistently zero
# here, not xterm's unsigned representation of its missing-parameter sentinel.
separate={'?25', 'arguments-63;;9'}
cases=[(name, c['sequence'], c['reply']) for name,c in source['cases'].items()
       if name not in separate]


def literal(text):
    return '"'+''.join('\\%03o'%b if b<32 or b>=127 else
        '\\'+chr(b) if chr(b) in '\\"' else chr(b) for b in text.encode())+'"'


outputs={
    'dec_status_oracle_cases.h':'/* Generated by tests/generate_dec_status_oracle.py. */\n'+
        'static const struct { const char *name, *sequence, *reply; } dec_status_oracle[] = {\n'+
        ''.join('    {'+', '.join(map(literal,c))+'},\n' for c in cases)+'};\n',
    'dec_status_oracle_cases.py':'# Generated by tests/generate_dec_status_oracle.py.\nCASES = [\n'+
        ''.join('    '+repr(c)+',\n' for c in cases)+']\n',
}
parser=argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check',action='store_true')
args=parser.parse_args()
for name,content in outputs.items():
    path=root/'tests'/name
    if args.check: assert path.read_text(encoding='utf-8')==content, 'Regenerate '+name
    else: path.write_text(content, encoding='utf-8', newline='\n')
