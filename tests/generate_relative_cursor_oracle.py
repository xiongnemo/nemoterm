"""Generate cursor-position expectations from independently retained XTerm replies."""
import argparse
import gzip
import hashlib
import json
from pathlib import Path

root = Path(__file__).resolve().parents[1]
manifest = json.loads((root/'research/cursor-movement-audit-validation.json').read_text(encoding='utf-8'))
cases = []
for prefix in ('cursor-audit', 'cursor-boundary-audit'):
    name = f'research/cursor-movement-audit-evidence/{prefix}-xterm.json.gz'
    entry = next(item for item in manifest['files'] if item['path'] == name)
    raw = gzip.decompress((root/name).read_bytes())
    assert hashlib.sha256(raw).hexdigest() == entry['raw_sha256']
    reference = json.loads(raw)
    assert reference['version'] == 'XTerm(412)'
    for label, case in reference['cases'].items():
        assert case['reply'].encode('utf-8').hex() == case['reply_hex']
        cases.append((prefix+'-'+label, case['sequence'], case['reply']))
assert len(cases) == 848

def literal(text):
    return '"' + ''.join('\\%03o' % byte if byte < 32 or byte >= 127 else
        '\\' + chr(byte) if chr(byte) in '\\"' else chr(byte)
        for byte in text.encode('utf-8')) + '"'

header = '/* Generated from retained independent XTerm(412) replies. */\n'
header += 'static const struct { const char *name, *sequence, *reply; } relative_cursor_oracle[] = {\n'
header += ''.join('    {'+', '.join(map(literal, case))+'},\n' for case in cases)+'};\n'
native = '# Generated by tests/generate_relative_cursor_oracle.py.\nCASES = [\n'
native += ''.join('    '+repr(case)+',\n' for case in cases)+']\n'
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
for name, text in [('relative_cursor_oracle_cases.h', header), ('relative_cursor_oracle_cases.py', native)]:
    path = root/'tests'/name
    if args.check:
        assert path.read_text(encoding='utf-8') == text, 'Regenerate '+name
    else:
        path.write_text(text, encoding='utf-8', newline='\n')
print('848 exact XTerm cursor-position sequences')
